export function detectLang() {
	const supported = ["en", "zh-TW", "zh-CN", "ja", "ko", "th", "vi"];
	const langs = navigator.languages || [navigator.language || "en"];
	for (const raw of langs) {
		const l = (raw || "").toLowerCase();
		if (l.startsWith("zh")) {
			if (l.includes("tw") || l.includes("hk") || l.includes("hant"))
				return "zh-TW";
			return "zh-CN";
		}
		const short = l.split("-")[0];
		if (supported.includes(short)) return short;
	}
	return "en";
}

export function getText(currentLang, key, replacements = {}) {
	let text =
		(i18nDict[currentLang] && i18nDict[currentLang][key]) ||
		i18nDict["zh-TW"][key] ||
		key;

	for (const [k, v] of Object.entries(replacements)) {
		text = text.replace(`{${k}}`, v);
	}
	return text;
}

export function applyTranslations(ui, currentLang) {
	document.querySelectorAll("[data-i18n]").forEach((el) => {
		el.textContent = getText(currentLang, el.getAttribute("data-i18n"));
	});
	document.querySelectorAll("[data-i18n-title]").forEach((el) => {
		el.title = getText(currentLang, el.getAttribute("data-i18n-title"));
	});
	document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
		el.setAttribute(
			"aria-label",
			getText(currentLang, el.getAttribute("data-i18n-aria-label")),
		);
	});
	if (ui.btnSwap) ui.btnSwap.title = getText(currentLang, "swapTitle");
	if (ui.btnSwapMobile)
		ui.btnSwapMobile.title = getText(currentLang, "swapTitle");
}
